/*  fetch-s2t.mjs — 抓 OpenCC 的簡→繁字典，寫成 _data/STCharacters.js。
 *
 *  為什麼需要它：`js/data.js` 的文案一律以繁體保存，執行時由 `toSimplified()`
 *  轉簡體顯示（見 docs/ARCHITECTURE.md）。而 `_data/artists/<id>/credits.json`
 *  的署名來自歌詞 sidecar 的製作人員行，那些檔案是簡體，若不轉成繁體，
 *  繁體模式下的署名會是簡體（實測 397 個署名裡有 179 個含簡繁差異字）。
 *
 *  與 _data/TSCharacters.js 的關係：兩者是同一份 OpenCC 字典的兩個方向。
 *  TS（繁→簡）已經內嵌進 js/data.js 供執行時轉換；ST（簡→繁）只在建構期
 *  抽取署名時用得到，所以它不進 data.js，只留在 _data/ 這一層。
 *
 *  用法：
 *    node _data/fetch-s2t.mjs                    # 直接抓 OpenCC（需要網路）
 *    node _data/fetch-s2t.mjs --from <檔案>      # 用本機已有的 STCharacters.txt
 *
 *  內容來自 https://github.com/BYVoid/OpenCC 的 data/dictionary/STCharacters.txt
 *  （Apache-2.0）。Node 的 fetch 不走系統代理，所以在本機抓不到時，
 *  可先用 PowerShell 下載再走 --from：
 *    Invoke-WebRequest <url> -OutFile "$env:TEMP\STCharacters.txt"
 *    node _data/fetch-s2t.mjs --from "$env:TEMP\STCharacters.txt"
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC =
  'https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/STCharacters.txt';
const OUT = path.join(here, 'STCharacters.js');

const argv = process.argv.slice(2);
const fromIdx = argv.indexOf('--from');
const fromFile = fromIdx >= 0 ? argv[fromIdx + 1] : null;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function download(url) {
  for (let attempt = 1; attempt <= 5; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': 'discography-showcase/1.0' } });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return await res.text();
    } catch (e) {
      if (attempt === 5)
        throw new Error(`${e.message}（Node 不走系統代理；請改走 --from，見本檔開頭的用法）`);
      await sleep(600 * attempt);
    }
  }
}

const text = fromFile ? fs.readFileSync(fromFile, 'utf8') : await download(SRC);

/* 格式（OpenCC 原始檔，TAB 分隔）：
 *   # 註解
 *   发<TAB>發 髮       ← 一個簡體字對多個繁體候選，候選以空白分隔、首選在前
 * 輸出沿用 TSCharacters.js 的形狀：export default "鍵 值1 值2|鍵 值|…"，
 * build.mjs 的 readDict() 取 `|` 分段、空白前第一段為鍵、其後為值，
 * 所以多候選要原樣保留（抽取署名時要靠候選數判斷這個字有沒有歧義）。 */
const entries = [];
for (const line of text.split(/\r?\n/)) {
  if (!line || line.startsWith('#')) continue;
  const parts = line.split('\t');
  if (parts.length < 2) continue;
  const key = parts[0].trim();
  const values = parts[1].trim().split(/\s+/).filter(Boolean);
  if (!key || !values.length) continue;
  /* 鍵與值都是單一漢字；含 `|` 或引號的列會破壞這個序列化格式，直接擋掉 */
  if (/[|"]/.test(line)) throw new Error('字典列含保留字元：' + line);
  entries.push(key + ' ' + values.join(' '));
}

if (entries.length < 1000) throw new Error(`字典條目過少（${entries.length}），來源可能已變更`);

const header = `/*  STCharacters.js - generated by _data/fetch-s2t.mjs
 *  OpenCC 簡體 -> 繁體 單字對照表（Apache-2.0，來源 BYVoid/OpenCC）。
 *  每個鍵的值可能有多個候選（首選在前）；抽取署名時以此判斷歧義：
 *  只有單一候選才自動轉換，多候選者保留原字或走人工對照表。
 *  不要手改；要更新請重跑 node _data/fetch-s2t.mjs                           */
`;

fs.writeFileSync(OUT, header + 'export default "' + entries.join('|') + '";\n', 'utf8');
console.log(
  `STCharacters.js written: ${entries.length} entries, ${(fs.statSync(OUT).size / 1024).toFixed(1)} KB`
);
